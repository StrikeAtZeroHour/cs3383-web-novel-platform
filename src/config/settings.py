def _resolve_secret_key(secret, debug):
    """Return a usable SECRET_KEY or raise when production has none.

    Pure helper so the guard can be unit-tested without reloading settings.
    """
    if secret:
        return secret
    if debug:
        return 'django-insecure-dev-only-key-change-in-production'
    raise ImproperlyConfigured(
        'DJANGO_SECRET_KEY environment variable is required when DEBUG is off.')


def _parse_hosts(value):
    """Split a comma-separated host list, dropping empty entries."""
    return [h for h in value.split(',') if h]


